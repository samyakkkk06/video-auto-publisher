"""One time helper to find your Instagram account id from a Facebook Page.

Run:  python -m scripts.instagram_setup

It lists your Facebook Pages, finds the Instagram professional account
linked to each one, and writes the id into .env for you.
"""
from __future__ import annotations

import sys

import requests

from .config import ROOT, load_config

GRAPH = "https://graph.facebook.com/v21.0"


def write_env(cfg, key: str, value: str) -> None:
    env_path = ROOT / ".env"
    lines = env_path.read_text(encoding="utf-8").splitlines() if env_path.exists() else []
    replaced = False
    for index, line in enumerate(lines):
        if line.strip().startswith(f"{key}="):
            lines[index] = f"{key}={value}"
            replaced = True
    if not replaced:
        lines.append(f"{key}={value}")
    env_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    cfg = load_config()
    token = cfg.env_get("INSTAGRAM_ACCESS_TOKEN")
    if not token:
        print("Put your access token in .env first:")
        print("  INSTAGRAM_ACCESS_TOKEN=EAAB...")
        print()
        print("Get one from the Graph API Explorer with the permissions:")
        print("  instagram_basic, instagram_content_publish,")
        print("  pages_read_engagement, pages_manage_posts")
        return 1

    print("\nChecking the token and listing your Facebook Pages...\n")
    response = requests.get(f"{GRAPH}/me/accounts", params={"access_token": token}, timeout=60)
    if response.status_code >= 400:
        print(f"Could not list pages: {response.status_code}")
        print(response.text[:600])
        print()
        print("Common causes:")
        print("  - the token expired, generate a new one")
        print("  - the token is missing pages_read_engagement")
        print("  - the token was not generated by the same app that owns the Page")
        return 1

    pages = response.json().get("data", [])
    if not pages:
        print("No Facebook Pages found for this token.")
        print("The Instagram account must be linked to a Facebook Page.")
        return 1

    print(f"Found {len(pages)} Facebook Page(s):\n")
    found = []
    for page in pages:
        page_id = page.get("id")
        page_name = page.get("name", "?")
        detail = requests.get(
            f"{GRAPH}/{page_id}",
            params={
                "fields": "name,instagram_business_account,access_token,username",
                "access_token": token,
            },
            timeout=60,
        )
        info = detail.json() if detail.status_code == 200 else {}
        ig = info.get("instagram_business_account") or {}
        ig_id = ig.get("id", "")
        ig_user = ig.get("username", "")
        print(f"  Page   : {page_name}")
        print(f"  IG id  : {ig_id or 'none linked'}")
        print(f"  IG user: {ig_user or '-'}")
        print()
        if ig_id:
            found.append((page_name, ig_id, ig_user))

    if not found:
        print("No linked Instagram professional account found.")
        print("In the Instagram app: Settings -> Account -> Switch to Professional -> Creator.")
        print("Then link it to a Facebook Page in Page settings -> Linked accounts.")
        return 1

    page_name, ig_id, ig_user = found[0]
    write_env(cfg, "INSTAGRAM_USER_ID", ig_id)
    print(f"Saved INSTAGRAM_USER_ID={ig_id} to .env")
    if ig_user:
        print(f"That is the account @{ig_user} on the page '{page_name}'.")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
